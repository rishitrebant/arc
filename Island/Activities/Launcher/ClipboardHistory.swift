import AppKit
import SwiftUI

/// One thing you copied.
struct ClipboardEntry: Identifiable, Equatable {

    enum Content: Equatable {
        case text(String)
        case image(Data)
        case files([URL])
    }

    let id = UUID()
    let content: Content

    /// One line for the list.
    var title: String {
        switch content {
        case .text(let text):
            return text
                .split(whereSeparator: \.isNewline)
                .first
                .map(String.init)?
                .trimmingCharacters(in: .whitespaces)
                ?? text
        case .image:
            return "Image"
        case .files(let urls):
            return urls.count == 1
                ? urls[0].lastPathComponent
                : "\(urls[0].lastPathComponent) and \(urls.count - 1) more"
        }
    }

    var symbolName: String {
        switch content {
        case .text(let text):
            return text.hasPrefix("http://") || text.hasPrefix("https://")
                ? "link"
                : "doc.text"
        case .image:
            return "photo"
        case .files:
            return "doc"
        }
    }
}

/// The last few things you copied, so the launcher can copy one again.
///
/// Memory only — nothing is ever written to disk. Skips anything a
/// password manager marks as concealed or transient (the
/// nspasteboard.org convention 1Password, Bitwarden, Keychain and others
/// follow), so passwords never land here.
@MainActor
final class ClipboardHistory: ObservableObject {

    @Published private(set) var entries: [ClipboardEntry] = []

    private static let maxEntries = 8
    private static let maxTextLength = 4_000
    private static let maxImageBytes = 6_000_000

    private static let skippedTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    ]

    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount

    func start() {

        guard timer == nil else { return }

        let timer = Timer(timeInterval: 0.6, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }

        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func clear() {
        entries.removeAll()
    }

    // MARK: - Reading

    private func poll() {

        let pasteboard = NSPasteboard.general

        guard pasteboard.changeCount != lastChangeCount else { return }

        lastChangeCount = pasteboard.changeCount

        guard AppSettings.keepClipboardHistory else {
            entries.removeAll()
            return
        }

        let types = pasteboard.types ?? []

        guard !types.contains(where: Self.skippedTypes.contains) else { return }

        guard let content = Self.read(pasteboard) else { return }

        let entry = ClipboardEntry(content: content)

        // Copying the same thing again moves it to the top.
        entries.removeAll { $0.content == content }
        entries.insert(entry, at: 0)

        if entries.count > Self.maxEntries {
            entries.removeLast(entries.count - Self.maxEntries)
        }
    }

    private static func read(_ pasteboard: NSPasteboard) -> ClipboardEntry.Content? {

        if
            let urls = pasteboard.readObjects(
                forClasses: [NSURL.self],
                options: [.urlReadingFileURLsOnly: true]
            ) as? [URL],
            !urls.isEmpty
        {
            return .files(urls)
        }

        if let text = pasteboard.string(forType: .string) {

            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)

            guard !trimmed.isEmpty else { return nil }

            return .text(String(trimmed.prefix(maxTextLength)))
        }

        if
            let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff),
            data.count <= maxImageBytes
        {
            return .image(data)
        }

        return nil
    }

    // MARK: - Copying back

    /// Puts an entry back on the clipboard.
    func copyBack(_ entry: ClipboardEntry) {

        let pasteboard = NSPasteboard.general

        pasteboard.clearContents()

        switch entry.content {

        case .text(let text):
            pasteboard.setString(text, forType: .string)

        case .image(let data):
            if let image = NSImage(data: data) {
                pasteboard.writeObjects([image])
            }

        case .files(let urls):
            pasteboard.writeObjects(urls as [NSURL])
        }

        // Don't treat our own write as a new copy. The list keeps its
        // order, so several items can be copied in a row without the
        // rows jumping under the cursor.
        lastChangeCount = pasteboard.changeCount
    }
}
